using Microsoft.EntityFrameworkCore;
using Vitrina.Api.Domain;

namespace Vitrina.Api.Data;

public sealed class VitrinaDbContext(DbContextOptions<VitrinaDbContext> options) : DbContext(options)
{
	public DbSet<UserAccount> Users => Set<UserAccount>();
	public DbSet<UserSession> Sessions => Set<UserSession>();
	public DbSet<EmailToken> EmailTokens => Set<EmailToken>();
	public DbSet<Company> Companies => Set<Company>();
	public DbSet<CompanyMember> CompanyMembers => Set<CompanyMember>();
	public DbSet<CaseProject> Cases => Set<CaseProject>();
	public DbSet<StudentProfile> StudentProfiles => Set<StudentProfile>();
	public DbSet<AuditEntry> AuditEntries => Set<AuditEntry>();
	public DbSet<CompanyInvitation> CompanyInvitations => Set<CompanyInvitation>();
	public DbSet<ReferenceEntry> ReferenceEntries => Set<ReferenceEntry>();
	public DbSet<CaseTeam> Teams => Set<CaseTeam>();
	public DbSet<CaseTeamMember> TeamMembers => Set<CaseTeamMember>();
	public DbSet<CaseTeamInvitation> TeamInvitations => Set<CaseTeamInvitation>();
	public DbSet<CaptainTransfer> CaptainTransfers => Set<CaptainTransfer>();
	public DbSet<CaseApplication> Applications => Set<CaseApplication>();
	public DbSet<CaseApplicationEvent> ApplicationEvents => Set<CaseApplicationEvent>();
	public DbSet<CaseParticipationHistory> ParticipationHistory => Set<CaseParticipationHistory>();
	public DbSet<CaseStage> CaseStages => Set<CaseStage>();
	public DbSet<CaseCheckpoint> CaseCheckpoints => Set<CaseCheckpoint>();
	public DbSet<SubmissionVersion> SubmissionVersions => Set<SubmissionVersion>();
	public DbSet<StoredFile> StoredFiles => Set<StoredFile>();
	public DbSet<NdaPolicy> NdaPolicies => Set<NdaPolicy>();
	public DbSet<NdaPolicyVersion> NdaPolicyVersions => Set<NdaPolicyVersion>();
	public DbSet<NdaAcceptance> NdaAcceptances => Set<NdaAcceptance>();
	public DbSet<SubmissionIdempotency> SubmissionIdempotencies => Set<SubmissionIdempotency>();
	public DbSet<TeamExecutionExclusion> TeamExecutionExclusions => Set<TeamExecutionExclusion>();
	public DbSet<CaseAward> CaseAwards => Set<CaseAward>();
	public DbSet<CaseResultPublication> CaseResultPublications => Set<CaseResultPublication>();
	public DbSet<ApplicationReview> ApplicationReviews => Set<ApplicationReview>();
	public DbSet<ApplicationReviewRevision> ApplicationReviewRevisions => Set<ApplicationReviewRevision>();
	public DbSet<UserNotification> Notifications => Set<UserNotification>();
	public DbSet<OutboxMessage> OutboxMessages => Set<OutboxMessage>();

	protected override void OnModelCreating(ModelBuilder modelBuilder)
	{
		modelBuilder.Entity<UserAccount>().HasIndex(x => x.Email).IsUnique();
		modelBuilder.Entity<UserAccount>().HasIndex(x => x.Nickname).IsUnique().HasFilter("\"Nickname\" IS NOT NULL");
		modelBuilder.Entity<UserAccount>().Property(x => x.GlobalRoles).HasColumnType("text[]");
		modelBuilder.Entity<UserAccount>().Property(x => x.GlobalPermissions).HasColumnType("text[]");
		modelBuilder.Entity<CompanyMember>().HasIndex(x => new { x.CompanyId, x.UserId }).IsUnique();
		modelBuilder.Entity<CompanyMember>().Property(x => x.Permissions).HasColumnType("text[]");
		modelBuilder.Entity<StudentProfile>().HasKey(x => x.UserId);
		modelBuilder.Entity<StudentProfile>().Property(x => x.Version).IsConcurrencyToken();
		modelBuilder.Entity<StudentProfile>().Property(x => x.SkillIds).HasColumnType("text[]");
		modelBuilder.Entity<StudentProfile>().Property(x => x.TechnologyIds).HasColumnType("text[]");
		modelBuilder.Entity<StudentProfile>().Property(x => x.Achievements).HasColumnType("text[]");
		modelBuilder.Entity<StudentProfile>().Property(x => x.PublicLinksJson).HasColumnType("text[]");
		modelBuilder.Entity<UserSession>().HasIndex(x => x.TokenHash).IsUnique();
		modelBuilder.Entity<EmailToken>().HasIndex(x => x.TokenHash).IsUnique();
		modelBuilder.Entity<CompanyInvitation>().HasIndex(x => x.TokenHash).IsUnique();
		modelBuilder.Entity<CompanyInvitation>().Property(x => x.Status).IsConcurrencyToken();
		modelBuilder.Entity<CompanyInvitation>().HasIndex(x => new { x.CompanyId, x.Email, x.Status });
		modelBuilder.Entity<ReferenceEntry>().HasIndex(x => new { x.Type, x.Name }).IsUnique();
		modelBuilder.Entity<Company>().HasMany(x => x.Members).WithOne().HasForeignKey(x => x.CompanyId);
		modelBuilder.Entity<CaseTeam>().HasIndex(x => new { x.CaseId, x.CaptainUserId });
		modelBuilder.Entity<CaseTeamMember>().HasIndex(x => new { x.TeamId, x.UserId }).IsUnique();
		modelBuilder.Entity<CaseTeamInvitation>().HasIndex(x => new { x.TeamId, x.InviteeUserId, x.Status });
		modelBuilder.Entity<CaseApplication>().Property(x => x.ParticipantUserIds).HasColumnType("uuid[]");
		modelBuilder.Entity<CaseApplication>().HasIndex(x => new { x.CaseId, x.Status });
		modelBuilder.Entity<CaseApplication>().HasIndex(x => x.PublicResultId).IsUnique();
		modelBuilder.Entity<CaseApplicationEvent>().HasIndex(x => new { x.ApplicationId, x.OccurredAt });
		modelBuilder.Entity<CaseParticipationHistory>().HasIndex(x => new { x.CaseId, x.UserId }).IsUnique();
		modelBuilder.Entity<CaseStage>().HasIndex(x => new { x.CaseId, x.Sequence }).IsUnique();
		modelBuilder.Entity<CaseStage>().Property(x => x.Version).IsConcurrencyToken();
		modelBuilder.Entity<CaseCheckpoint>().HasIndex(x => new { x.StageId, x.Title });
		modelBuilder.Entity<CaseCheckpoint>().HasIndex(x => x.CaseId);
		modelBuilder.Entity<CaseCheckpoint>().Property(x => x.Version).IsConcurrencyToken();
		modelBuilder.Entity<CaseCheckpoint>().Property(x => x.PassingTeamIds).HasColumnType("uuid[]");
		modelBuilder.Entity<CaseCheckpoint>().Property(x => x.PassingSoloApplicationIds).HasColumnType("uuid[]");
		modelBuilder.Entity<SubmissionVersion>().HasIndex(x => new { x.CheckpointId, x.ApplicationId, x.Version }).IsUnique();
		modelBuilder.Entity<SubmissionVersion>().HasIndex(x => x.CaseId);
		modelBuilder.Entity<SubmissionVersion>().Property(x => x.FileIds).HasColumnType("uuid[]");
		modelBuilder.Entity<SubmissionVersion>().Property(x => x.LinksJson).HasColumnType("jsonb");
		modelBuilder.Entity<StoredFile>().HasIndex(x => x.ObjectKey).IsUnique();
		modelBuilder.Entity<StoredFile>().HasIndex(x => new { x.ApplicationId, x.Purpose });
		modelBuilder.Entity<StoredFile>().HasIndex(x => new { x.CaseId, x.StageId, x.Status });
		modelBuilder.Entity<NdaPolicy>().HasIndex(x => x.CaseId).IsUnique();
		modelBuilder.Entity<NdaPolicyVersion>().HasIndex(x => new { x.CaseId, x.Version }).IsUnique();
		modelBuilder.Entity<NdaAcceptance>().HasIndex(x => new { x.ApplicationId, x.UserId, x.Version }).IsUnique();
		modelBuilder.Entity<SubmissionIdempotency>().HasIndex(x => new { x.UserId, x.CheckpointId, x.Key }).IsUnique();
		modelBuilder.Entity<TeamExecutionExclusion>().HasIndex(x => x.TeamId).IsUnique();
		modelBuilder.Entity<TeamExecutionExclusion>().HasIndex(x => x.CaseId);
		modelBuilder.Entity<CaseAward>().HasIndex(x => new { x.CaseId, x.ApplicationId, x.Category });
		modelBuilder.Entity<CaseResultPublication>().HasIndex(x => x.CaseId).IsUnique();
		modelBuilder.Entity<CaseResultPublication>().Property(x => x.Version).IsConcurrencyToken();
		modelBuilder.Entity<CaseAward>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<CaseAward>().HasOne<CaseApplication>().WithMany().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<CaseResultPublication>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<CaseProject>().Property(x => x.NominationNames).HasColumnType("text[]");
		modelBuilder.Entity<ApplicationReview>().HasIndex(x => x.ApplicationId).IsUnique();
		modelBuilder.Entity<ApplicationReview>().Property(x => x.Version).IsConcurrencyToken();
		modelBuilder.Entity<ApplicationReview>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<ApplicationReview>().HasOne<CaseApplication>().WithMany().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<ApplicationReviewRevision>().HasIndex(x => new { x.ReviewId, x.Version }).IsUnique();
		modelBuilder.Entity<ApplicationReviewRevision>().HasOne<ApplicationReview>().WithMany().HasForeignKey(x => x.ReviewId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<OutboxMessage>().Property(x => x.PayloadJson).HasColumnType("jsonb");
		modelBuilder.Entity<UserNotification>().HasOne<UserAccount>().WithMany()
			.HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<UserNotification>().HasIndex(x => new { x.UserId, x.CreatedAt });
		modelBuilder.Entity<UserNotification>().HasIndex(x => new { x.UserId, x.ReadAt });
		modelBuilder.Entity<OutboxMessage>().HasIndex(x => new { x.ProcessedAt, x.AvailableAt, x.OccurredAt });

		modelBuilder.Entity<CaseStage>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<CaseCheckpoint>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<CaseCheckpoint>().HasOne<CaseStage>().WithMany().HasForeignKey(x => x.StageId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<SubmissionVersion>().HasOne<CaseCheckpoint>().WithMany().HasForeignKey(x => x.CheckpointId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<SubmissionVersion>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<SubmissionVersion>().HasOne<CaseApplication>().WithMany().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<SubmissionVersion>().HasOne<UserAccount>().WithMany().HasForeignKey(x => x.SubmittedByUserId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<StoredFile>().HasOne<UserAccount>().WithMany().HasForeignKey(x => x.OwnerUserId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<StoredFile>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<StoredFile>().HasOne<CaseStage>().WithMany().HasForeignKey(x => x.StageId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<StoredFile>().HasOne<CaseCheckpoint>().WithMany().HasForeignKey(x => x.CheckpointId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<StoredFile>().HasOne<CaseApplication>().WithMany().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<NdaPolicy>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Cascade);
		modelBuilder.Entity<NdaPolicyVersion>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<NdaPolicyVersion>().HasOne<UserAccount>().WithMany().HasForeignKey(x => x.CreatedByUserId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<NdaAcceptance>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<NdaAcceptance>().HasOne<CaseApplication>().WithMany().HasForeignKey(x => x.ApplicationId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<NdaAcceptance>().HasOne<UserAccount>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<SubmissionIdempotency>().HasOne<UserAccount>().WithMany().HasForeignKey(x => x.UserId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<SubmissionIdempotency>().HasOne<CaseCheckpoint>().WithMany().HasForeignKey(x => x.CheckpointId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<TeamExecutionExclusion>().HasOne<CaseTeam>().WithMany().HasForeignKey(x => x.TeamId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<TeamExecutionExclusion>().HasOne<CaseProject>().WithMany().HasForeignKey(x => x.CaseId).OnDelete(DeleteBehavior.Restrict);
		modelBuilder.Entity<TeamExecutionExclusion>().HasOne<UserAccount>().WithMany().HasForeignKey(x => x.ExcludedByUserId).OnDelete(DeleteBehavior.Restrict);
	}
}
